import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { writeFile } from 'node:fs/promises';
if(!process.argv.includes('--confirm-disposable'))throw new Error('Requires --confirm-disposable on an isolated test instance.');
const base='http://127.0.0.1:3022';
const get=async p=>{const r=await fetch(base+p);assert.equal(r.status,200,p);return r.json();};
const put=async(s,revision)=>fetch(base+'/api/workspace',{method:'PUT',headers:{'Content-Type':'application/json',Origin:base},body:JSON.stringify({state:s,revision})});
assert.equal((await get('/api/health')).instance,createHash('sha256').update(resolve('.').toLowerCase()).digest('hex').slice(0,16));
assert.equal((await get('/api/ai-settings')).configured,false);
const original=await get('/api/workspace');
assert.equal(original.state.courses.length,1);assert.equal(original.state.courses[0].id,'demo-linear');
assert.ok(original.state.courses[0].studyLab.practice.attempts.length>=2,'Run UI tests first');
const state=structuredClone(original.state);
const attachment=state.courses[0].materials.find(m=>m.fileId);
state.noteDraft={note:{...state.notes[0],id:'integration-draft',title:'完整迁移草稿',sources:[{id:'S1',name:attachment.name,fileId:attachment.fileId,section:'校验',quote:'测试原文'}]},origin:null};
const saved=await put(state,original.revision);assert.equal(saved.status,200);const revision=(await saved.json()).revision;
const bundle=await get('/api/backup');assert.equal(bundle.state.noteDraft.note.title,'完整迁移草稿');
const response=await fetch(base+'/api/backup',{method:'POST',headers:{'Content-Type':'application/json',Origin:base},body:JSON.stringify({backup:bundle,revision})});assert.equal(response.status,200);
const restored=await response.json();
assert.deepEqual(restored.state.courses[0].studyLab.practice.attempts,bundle.state.courses[0].studyLab.practice.attempts);
assert.notEqual(restored.state.noteDraft.note.sources[0].fileId,attachment.fileId);
const snapshots=(await get('/api/snapshots')).snapshots.filter(s=>s.reason==='before-restore');
assert.ok(snapshots.length);
const before=await get('/api/backup?snapshot='+snapshots[0].id);
assert.equal(before.state.noteDraft.note.title,'完整迁移草稿');
assert.equal(before.state.noteDraft.note.sources[0].fileId,attachment.fileId);
assert.equal((await put(state,revision)).status,409);
const corrupt=structuredClone(restored.state);corrupt.courses[0].studyLab.practice.attempts[0].answer=99;
assert.equal((await put(corrupt,restored.revision)).status,400);
assert.deepEqual((await get('/api/workspace')).state,restored.state);
// Clear only our injected draft; retain prior test results and remapped files.
const cleaned={...restored.state,noteDraft:original.state.noteDraft??{note:null,origin:null}};
assert.equal((await put(cleaned,restored.revision)).status,200);
const report={verifiedAt:new Date().toISOString(),realD1R2:true,practiceHistoryRoundtrip:true,draftAttachmentRemap:true,beforeRestoreSnapshotComplete:true,staleWriterRejected:true,malformedAttemptRejected:true,failedWritePreservedWorkspace:true};
await writeFile('docs/evaluation/update-api.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
